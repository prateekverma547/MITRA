"""Migrations: how the schema changes, and what happens when it does not match.

Sync tests drive Alembic itself, which runs its own event loop, so they cannot run
inside an async test. The async tests exercise the app's startup check.

Each test works on its own SQLite file. The Postgres path is exercised by the backup
drill in docs/OPERATIONS.md, which these tests cannot stand in for.
"""

import asyncio
import sqlite3

import pytest
from alembic import command
from alembic.config import Config
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy import Column, String

from app import db
from app.migrations import ALEMBIC_INI, SchemaBehind, SchemaNotMigrated, head_revision

BASELINE = "315a320c1de2"
HEAD = "0005_interview_recording_enabled"
PREVIOUS = "0004_admin_revocations"


@pytest.fixture
def sqlite_path(tmp_path, monkeypatch):
    path = tmp_path / "migrated.db"
    monkeypatch.setenv("DATABASE_URL", f"sqlite+aiosqlite:///{path}")
    return path


def alembic_config() -> Config:
    return Config(str(ALEMBIC_INI))


def version_of(path) -> list[str]:
    with sqlite3.connect(path) as conn:
        return [r[0] for r in conn.execute("SELECT version_num FROM alembic_version")]


def raw(path, sql: str, params=()) -> None:
    with sqlite3.connect(path) as conn:
        conn.execute(sql, params)


# --- the head and the upgrade path ------------------------------------------


def test_head_is_read_from_the_revision_scripts():
    assert head_revision() == HEAD


def test_upgrading_a_new_database_reaches_head(sqlite_path):
    command.upgrade(alembic_config(), "head")
    assert version_of(sqlite_path) == [HEAD]


def test_the_partial_unique_index_exists_after_upgrade(sqlite_path):
    command.upgrade(alembic_config(), "head")
    with sqlite3.connect(sqlite_path) as conn:
        names = {r[0] for r in conn.execute("SELECT name FROM sqlite_master WHERE type='index'")}
    assert "uq_interviews_one_live_per_candidate" in names


def test_existing_rows_survive_an_upgrade(sqlite_path):
    command.upgrade(alembic_config(), BASELINE)
    raw(
        sqlite_path,
        "INSERT INTO jobs (id, source_filename, jd_text, spec_status) "
        "VALUES ('job_keep', 'jd.txt', 'text', 'ready')",
    )

    command.upgrade(alembic_config(), "head")

    with sqlite3.connect(sqlite_path) as conn:
        assert [r[0] for r in conn.execute("SELECT id FROM jobs")] == ["job_keep"]


def test_the_latest_revision_downgrades_and_upgrades_again(sqlite_path):
    command.upgrade(alembic_config(), "head")
    command.downgrade(alembic_config(), "-1")
    assert version_of(sqlite_path) == [PREVIOUS]

    command.upgrade(alembic_config(), "head")
    assert version_of(sqlite_path) == [HEAD]


def test_upgrade_refuses_when_two_live_sessions_already_exist(sqlite_path):
    """Two live rows for one candidate cannot be fixed by the database. The upgrade must
    stop, and say so, rather than pick one to keep."""
    command.upgrade(alembic_config(), BASELINE)
    raw(
        sqlite_path,
        "INSERT INTO candidates (id, job_id, name, cv_text, blueprint_status) "
        "VALUES ('cand_dup', 'job_x', 'Dup', 'cv', 'pending')",
    )
    for interview_id, meeting in (("int_a", "111111111"), ("int_b", "222222222")):
        raw(
            sqlite_path,
            "INSERT INTO interviews (id, candidate_id, meeting_id, password, "
            "daily_room_name, daily_room_url, room_expires_at, status) "
            "VALUES (?, 'cand_dup', ?, 'pw', 'room', 'https://x', "
            "'2030-01-01 00:00:00', 'scheduled')",
            (interview_id, meeting),
        )

    with pytest.raises(Exception, match="UNIQUE|unique"):
        command.upgrade(alembic_config(), "head")


def test_the_index_revision_is_idempotent_on_a_database_that_already_has_it(sqlite_path):
    """An earlier local run created the index before migrations existed."""
    command.upgrade(alembic_config(), BASELINE)
    raw(
        sqlite_path,
        "CREATE UNIQUE INDEX uq_interviews_one_live_per_candidate ON interviews "
        "(candidate_id) WHERE status IN ('scheduled', 'in_progress')",
    )

    command.upgrade(alembic_config(), "head")

    assert version_of(sqlite_path) == [HEAD]


# --- the models and the migrations must agree ---------------------------------


def test_the_models_match_the_migrated_schema(sqlite_path):
    command.upgrade(alembic_config(), "head")
    command.check(alembic_config())  # raises if the models have drifted


def test_a_model_change_without_a_revision_is_caught(sqlite_path):
    """The guard this whole arrangement exists for: adding a column to a model and
    forgetting the migration must fail here, not in production."""
    command.upgrade(alembic_config(), "head")
    table = db.Candidate.__table__
    table.append_column(Column("unmigrated_probe", String, nullable=True))
    try:
        with pytest.raises(AutogenerateDiffsDetected):
            command.check(alembic_config())
    finally:
        table._columns.remove(table.c.unmigrated_probe)


# --- the app's startup check --------------------------------------------------


async def test_a_fresh_database_is_created_and_stamped_at_head(sqlite_path):
    await db.reset_engine()
    try:
        await db.create_all()
        assert version_of(sqlite_path) == [HEAD]
    finally:
        await db.reset_engine()


async def test_the_app_refuses_a_database_with_tables_but_no_migration_record(sqlite_path):
    """Made before migrations existed. Its schema is unknown, so it is not trusted."""
    await db.reset_engine()
    try:
        async with db.get_engine().begin() as connection:
            await connection.run_sync(db.Base.metadata.create_all)
        with pytest.raises(SchemaNotMigrated, match="stamp"):
            await db.create_all()
    finally:
        await db.reset_engine()


async def test_the_app_refuses_a_database_behind_head(sqlite_path):
    # Alembic runs its own event loop, so it goes to a thread from inside this one.
    await asyncio.to_thread(command.upgrade, alembic_config(), BASELINE)
    await db.reset_engine()
    try:
        with pytest.raises(SchemaBehind, match="upgrade head"):
            await db.create_all()
    finally:
        await db.reset_engine()


async def test_the_app_starts_on_a_database_at_head(sqlite_path):
    await asyncio.to_thread(command.upgrade, alembic_config(), "head")
    await db.reset_engine()
    try:
        await db.create_all()  # no error
    finally:
        await db.reset_engine()
